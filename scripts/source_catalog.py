"""Curated source catalogue for Top 10 Everything.

Every source record is deliberately conservative about licensing and limits.
Where a fact could not be confirmed from the provider's documentation, the
field is left as None / "unclear" instead of being guessed.

`test_url` is a small, representative request used by scripts/verify_sources.py.
It is NOT necessarily the endpoint you should use for production ingestion.
"""

