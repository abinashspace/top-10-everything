"""Topic taxonomy for Top 10 Everything.

Design principles:
- A topic is included only if a defensible ranking question can be stated.
- `data_availability` describes whether free, legally usable data can actually
  support that question today, not whether the topic is interesting.
- Proprietary rankings (QS, Michelin, Forbes, ...) are recorded as reference
  sources only and are never treated as free data.
"""

from __future__ import annotations


def T(slug, name, subcats, bundle, method, metric, availability, *, freq="monthly",
      status=None, caveats=None, geo=None, primary=None, backup=None, question=None):
    return {
        "slug": slug,
        "name": name,
        "subcategories": subcats,
        "bundle": bundle,
        "method": method,
        "metric": metric,
        "availability": availability,
        "frequency": freq,
        "status": status,
        "caveats": caveats or [],
        "geo": geo or ["global"],
        "primary": primary,
        "backup": backup,
        "question": question,
    }


